#include <bits/stdc++.h>
using namespace std; 

int main() {
    // Variable declarations
    int a = 10;                      // Integer variable
    double b = 5.5;                  // Double (floating-point) variable
    float f = 3.14f;                 // Float variable
    char c = 'A';                    // Character variable
    string str = "I'm learning C++"; // String variable
    bool flag = true;                // Boolean variable

    // Output the variables
    cout << "Integer a: " << a << endl;
    cout << "Double b: " << b << endl;
    cout << "Character c: " << c << endl;
    cout << "Float f: " << f << endl;
    cout << "String str: " << str << endl;
    cout << "Boolean flag: " << (flag ? "true" : "false") << endl;

    return 0;
}